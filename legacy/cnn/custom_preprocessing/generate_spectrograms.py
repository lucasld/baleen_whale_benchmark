import scipy
import os
import pathlib
import numpy as np
import json
from PIL import Image
import argparse
import glob
import re # Import regex module


def generate_spectrograms_for_site(site_output_dir, spectrograms_output_dir, clips_output_dir, class_counters, expected_classes=None):
    """
    Generates spectrograms from Koogu-processed data (.npz files) for a specific site.
    Organizes output by class folders and uses shared counters.
    
    Args:
        site_output_dir: Path to the site's Koogu output directory containing .npz files
        spectrograms_output_dir: Base path where spectrogram class folders are located
        clips_output_dir: Path where audio clips will be saved for this site
        class_counters: Dictionary holding the current count for each class (will be updated)
        expected_classes: List of expected class names to validate against (optional)
        
    Returns:
        bool: True if successful, False otherwise.
    """
    site_name = os.path.basename(site_output_dir)
    print(f"--- Generating Spectrograms for Site: {site_name} ---")
    
    # --- NEW CODE: Extract YEAR from site_name ---
    # The site_name is expected to be in format "LocationYYYY" (e.g., "BallenyIslands2015")
    # Extract the YEAR from site_name for later use
    site_year_match = re.search(r'(\d{4})$', site_name)
    if site_year_match:
        site_year = site_year_match.group(1)  # e.g., "2015"
        print(f"  Extracted year {site_year} from site name {site_name}")
    else:
        # Default if no year found
        site_year = "0000"
        print(f"  Warning: Could not extract year from site name {site_name}. Using default.")
    # --- END NEW CODE ---
    
    # Create site-specific clips directory
    site_clips_dir = os.path.join(clips_output_dir, site_name, 'AnimalSpot')
    os.makedirs(site_clips_dir, exist_ok=True)
    
    # Settings for audio clips (must match the ones used in Koogu)
    audio_settings = {
        'clip_length': 15.0,
        'clip_advance': 2.5,
        'desired_fs': 250
    }
    
    # Settings for converting audio to a time-frequency representation
    spec_settings = {
        'win_len': 256,
        'win_overlap': 250,
        'nfft': 3570,
        'bandwidth_clip': [5, 124]
    }
    
    # Find all .npz files and classes_list.json in the site's output directory
    npz_files = glob.glob(os.path.join(site_output_dir, '*.npz'))
    # Use the classes list generated by Koogu
    classes_file = os.path.join(site_output_dir, 'classes_list.json') 
    
    if not os.path.exists(classes_file):
        print(f"Error: classes_list.json not found in {site_output_dir}")
        # Attempt to fall back to detected_classes.json if it exists
        classes_file = os.path.join(site_output_dir, 'detected_classes.json')
        if not os.path.exists(classes_file):
             print(f"Error: Neither classes_list.json nor detected_classes.json found in {site_output_dir}")
             return False
        else:
             print(f"Warning: Using detected_classes.json as classes_list.json was not found.")

    
    # Load class labels
    try:
        with open(classes_file, 'r') as f:
            label_list = json.load(f)
    except Exception as e:
        print(f"Error reading class list file {classes_file}: {e}")
        return False

    
    print(f"Found {len(npz_files)} .npz files and {len(label_list)} classes for site {site_name}")
    
    # Validate class names if expected_classes is provided
    if expected_classes:
        unknown_classes = [c for c in label_list if c not in expected_classes and c != 'Noise']
        if unknown_classes:
             # Raise an error instead of asking for input
            error_message = (
                f"ERROR: Site '{site_name}' uses classes not in expected categories: {unknown_classes}. "
                f"Expected: {expected_classes}. Please check Koogu output or config."
            )
            raise ValueError(error_message)
    
    # Ensure directories exist for all classes found in this site
    for class_name in label_list:
        class_dir = os.path.join(spectrograms_output_dir, class_name)
        os.makedirs(class_dir, exist_ok=True)
        # Ensure counter exists for this class
        if class_name not in class_counters:
            class_counters[class_name] = 0 
            print(f"Initializing counter for new class: {class_name}")

    # Process each .npz file (each corresponds to an original audio file)
    for zipped_location in npz_files:
        print(f"  Processing Koogu file: {os.path.basename(zipped_location)}")
        
        # Load the data
        try:
            data = np.load(zipped_location)
            wavs = data['clips']
            labels = data['labels']
        except Exception as e:
            print(f"  Error loading data from {zipped_location}: {e}")
            continue # Skip this file

        # Extract filename info for tracking purposes only
        # We don't need this for location_year anymore, but keep it for clip labels
        filename = os.path.basename(zipped_location)
        filename_base = filename.replace('.wav.npz', '')  # e.g., "20150510_100000"
        
        # --- SIMPLIFIED: We already have location_year from the site name ---
        # Use the site_name which already contains the location + year
        location_year = site_name  # e.g., "BallenyIslands2015"
        
        # Save questionable labels file (labels that don't sum to 1) to site clips dir
        csv_name = f"{filename_base}_questionable-labels.csv"
        csv_path = os.path.join(site_clips_dir, csv_name)
        questionable_labels = np.around(labels[labels.sum(axis=1) != 1], 2)
        
        if questionable_labels.size > 0:
            try:
                np.savetxt(csv_path, questionable_labels, delimiter=',', 
                          header=','.join(label_list[:]), comments='', fmt="%.2f")
                # print(f"  {len(questionable_labels)} questionable labels saved to {csv_name}") # Less verbose
            except Exception as e:
                 print(f"  Warning: Could not save questionable labels to {csv_path}: {e}")
        
        # Process each clip (wav) in the file
        clips_processed_count = 0
        for x, wav in enumerate(wavs):
            try:
                # Create label for clip
                label = labels[x, :]
                
                # Handle multi-class case (one-hot encoding)
                if label.shape[0] == len(label_list):
                    # Convert to integer labels
                    label = label.astype(int)
                    # Find which classes this clip belongs to
                    class_indices = np.where(label == 1)[0]
                    
                    if len(class_indices) == 0:
                        # print(f"  Warning: Clip {x} in {filename} has no classes assigned") # Less verbose
                        continue
                    
                    # Select a random class if multiple are assigned
                    # This matches original script's logic, but might not be ideal
                    # Consider alternatives if needed (e.g., save for all classes)
                    idx = np.random.randint(len(class_indices))
                    selected_class_idx = class_indices[idx]
                    CLASSNAME = label_list[selected_class_idx]
                else:
                    # Simple case: direct class index (assuming single label per clip)
                    # Ensure the index is valid
                    label_idx = int(label[0])
                    if 0 <= label_idx < len(label_list):
                         CLASSNAME = label_list[label_idx]
                    else:
                         print(f"  Warning: Clip {x} in {filename} has invalid label index {label_idx}")
                         continue
                    
                # Calculate clip times
                ID = x
                STARTTIMES = int(x * audio_settings['clip_advance'] * 1000)
                ENDTIMES = int(STARTTIMES + audio_settings['clip_length'] * 1000)
                
                # Create label for clip file - Use filename_base (e.g., "20150510_100000")
                clip_label = f"{CLASSNAME}-_{ID}_{site_year}_{filename_base}_{STARTTIMES}_{ENDTIMES}.wav"
                
                # Count this class occurrence for the spectrogram ID (needs to be unique per class)
                class_counters[CLASSNAME] += 1
                spec_ID = class_counters[CLASSNAME]
                
                # Create label for spectrogram matching the expected format: n_locationyear_class.png
                spec_label = f"{spec_ID}_{location_year}_{CLASSNAME}.png"
                
                # Filter wav (bandpass filter exactly as in original script)
                sos = scipy.signal.iirfilter(20, spec_settings['bandwidth_clip'], rp=None, rs=None, 
                                             btype='band', analog=False, ftype='butter', 
                                             output='sos', fs=audio_settings['desired_fs'])
                filtered_wav = scipy.signal.sosfilt(sos, wav)
                
                # Save clip
                clip_path = os.path.join(site_clips_dir, clip_label)
                scipy.io.wavfile.write(clip_path, audio_settings['desired_fs'], filtered_wav)
                
                # Create and save spectrogram using exactly the same parameters
                f, t, Sxx = scipy.signal.spectrogram(
                    filtered_wav, 
                    fs=audio_settings['desired_fs'], 
                    window='hamming',
                    nperseg=spec_settings['win_len'],
                    noverlap=spec_settings['win_overlap'], 
                    nfft=spec_settings['nfft'],
                    detrend=False,
                    return_onesided=True, 
                    scaling='density', 
                    axis=-1, 
                    mode='magnitude'
                )
                
                # Process spectrogram exactly as in original script
                Sxx = 1 - Sxx
                per = np.percentile(Sxx.flatten(), 98)
                I = (Sxx - Sxx.min()) / (per - Sxx.min())
                I[I > 1] = 1
                im = np.array(I * 255, dtype=np.uint8)
                im = Image.fromarray(np.flipud(im))
                im = im.resize((30, 90), Image.Resampling.LANCZOS)
                
                # Save spectrogram to the appropriate class directory
                spec_path = os.path.join(spectrograms_output_dir, CLASSNAME, spec_label)
                im.save(spec_path)
                clips_processed_count += 1
                
            except Exception as clip_error:
                print(f"  Error processing clip {x} from {filename}: {clip_error}")
                # Continue to the next clip
        
        print(f"  Completed processing {clips_processed_count}/{len(wavs)} clips from {os.path.basename(zipped_location)}")
        
    print(f"--- Finished Spectrogram Generation for Site: {site_name} ---")
    return True

# Define a new function to orchestrate spectrogram generation for all sites
def run_spectrogram_generation(koogu_output_dir, spectrograms_output_dir, clips_output_dir, config_path=None, site_to_process=None):
    """Finds all site outputs from Koogu and generates spectrograms."""
    print(f"Starting spectrogram generation.")
    print(f"Koogu input source: {koogu_output_dir}")
    print(f"Spectrogram output: {spectrograms_output_dir}")
    print(f"Clips output: {clips_output_dir}")

    # Load expected classes from config if provided (used for validation)
    expected_classes = None
    if config_path:
        try:
            with open(config_path, 'r') as f:
                config = json.load(f)
                expected_classes = config.get('CATEGORIES', [])
                if expected_classes:
                    print(f"Loaded {len(expected_classes)} expected classes from config for validation: {expected_classes}")
        except Exception as e:
            print(f"Error loading config file '{config_path}': {e}. Proceeding without category validation.")

    # Find all site directories in the Koogu output directory
    if not os.path.isdir(koogu_output_dir):
        print(f"Error: Koogu output directory not found: {koogu_output_dir}")
        return [site_to_process] if site_to_process else []
        
    if site_to_process:
        site_dirs = [os.path.join(koogu_output_dir, site_to_process)]
        if not os.path.isdir(site_dirs[0]):
            print(f"Error: Specified site directory not found: {site_dirs[0]}")
            return [site_to_process]
    else:
        site_dirs = [os.path.join(koogu_output_dir, d) for d in os.listdir(koogu_output_dir) 
                     if os.path.isdir(os.path.join(koogu_output_dir, d))]
    
    if not site_dirs:
        print(f"No site directories found in Koogu output path: {koogu_output_dir}")
        return []
    
    print(f"Found {len(site_dirs)} sites to process: {', '.join([os.path.basename(d) for d in site_dirs])}")
    
    # Keep track of class counts across all sites
    class_counters = {}
    counter_file = os.path.join(spectrograms_output_dir, '..', 'class_counters.json') # Store counter one level up
    if os.path.exists(counter_file):
        try:
            with open(counter_file, 'r') as f:
                class_counters = json.load(f)
                print(f"Loaded existing class counters: {class_counters}")
        except Exception as e:
            print(f"Could not load existing counters from {counter_file}, starting fresh: {e}")
            class_counters = {} # Ensure it's a dict

    failed_sites = []
    # Process each site
    for site_dir in site_dirs:
        site_name = os.path.basename(site_dir)
        try:
            success = generate_spectrograms_for_site(
                 site_dir, spectrograms_output_dir, clips_output_dir, 
                 class_counters, # Pass the shared counter dict
                 expected_classes
            )
            if not success:
                 failed_sites.append(site_name)
                 print(f"Spectrogram generation failed for site: {site_name}")
        except ValueError as ve:
             print(ve) # Print the specific validation error
             failed_sites.append(site_name)
             print(f"Validation error in site: {site_name} - continuing with other sites")
        except Exception as e:
            failed_sites.append(site_name)
            print(f"An unexpected error occurred while generating spectrograms for site {site_name}: {e}")
            
    # Save the final counter file
    try:
        with open(counter_file, 'w') as f:
            json.dump(class_counters, f, indent=2)
        print(f"Saved final class counters to {counter_file}")
    except Exception as e:
        print(f"Warning: Could not save final class counters: {e}")

    if not failed_sites:
        print("\nAll sites processed successfully for spectrogram generation.")
        print(f"Final spectrogram counts per class: {class_counters}")
    else:
        print(f"\nSpectrogram generation completed with {len(failed_sites)} failed sites.")
        
    return failed_sites

# Keep the __main__ block for potential direct execution
if __name__ == "__main__":
    parser = argparse.ArgumentParser(description='Generate spectrograms from Koogu-processed data')
    # Use more specific names to avoid conflict when importing
    parser.add_argument('--koogu_input', type=str, required=True,
                        help='Directory containing Koogu output with site subdirectories')
    parser.add_argument('--spec_output', type=str, required=True,
                        help='Directory to store the spectrograms (will have class subfolders)')
    parser.add_argument('--clip_output', type=str, required=True,
                        help='Base directory to store the audio clips (will have site subfolders)')
    parser.add_argument('--site_name', type=str, default=None,
                        help='Process only the specified site (optional)')
    parser.add_argument('--config_file', type=str, default=None,
                        help='Path to config.json to validate class names (optional)')
    
    args = parser.parse_args()
    
    # Setup paths for direct execution
    os.makedirs(args.spec_output, exist_ok=True)
    os.makedirs(args.clip_output, exist_ok=True)
    
    run_spectrogram_generation(args.koogu_input, args.spec_output, args.clip_output, 
                               args.config_file, args.site_name) 