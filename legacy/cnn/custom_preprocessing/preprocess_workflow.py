#!/usr/bin/env python3
import os
import sys
import argparse
import json
import shutil
from pathlib import Path

# Import the refactored functions from the other scripts
from process_all_sites import run_all_sites_processing
from generate_spectrograms import run_spectrogram_generation


def main():
    parser = argparse.ArgumentParser(
        description='Run the simplified preprocessing workflow for baleen whale detection.'
                    ' Creates annotations, runs Koogu, and generates spectrograms.',
        formatter_class=argparse.ArgumentDefaultsHelpFormatter
    )
    parser.add_argument('--raw_data', type=str, required=True,
                        help='Path to the base directory containing raw data site subdirectories (e.g., ./data/raw).')
    parser.add_argument('--output', type=str, required=True,
                        help='Path to the base output directory where subfolders (annotations, koogu_output, etc.) will be created.')
    parser.add_argument('--config', type=str, default='config.json',
                        help='Path to the project config.json file (used for validating class names).')
    parser.add_argument('--tag_mapping', type=str, default=None,
                        help='Path to the tag_mapping.json file (maps annotation tags to expected class names). '
                             'Default is tag_mapping.json in the custom_preprocessing directory.')
    parser.add_argument('--skip_koogu', action='store_true',
                        help='Skip the annotation processing and Koogu execution (Stage 1) and only generate spectrograms from existing Koogu output.')
    parser.add_argument('--site', type=str, default=None,
                        help='Process only the specified site name (optional). If set, applies to both stages.')

    args = parser.parse_args()

    # --- Setup Paths --- 
    # Use absolute paths for clarity
    raw_data_dir = os.path.abspath(args.raw_data)
    output_dir = os.path.abspath(args.output)
    config_path = os.path.abspath(args.config) if args.config else None
    tag_mapping_path = os.path.abspath(args.tag_mapping) if args.tag_mapping else None

    # Define the structured output directories
    annotations_dir = os.path.join(output_dir, 'annotations')
    koogu_output_dir = os.path.join(output_dir, 'koogu_output')
    spectrograms_dir = os.path.join(output_dir, 'spectrograms')
    clips_dir = os.path.join(output_dir, 'clips') # Clips are still generated by generate_spectrograms

    # Create output directories if they don't exist
    os.makedirs(annotations_dir, exist_ok=True)
    os.makedirs(koogu_output_dir, exist_ok=True)
    os.makedirs(spectrograms_dir, exist_ok=True)
    os.makedirs(clips_dir, exist_ok=True)

    print("--- Preprocessing Workflow Started ---")
    print(f"Raw Data Input: {raw_data_dir}")
    print(f"Main Output Directory: {output_dir}")
    
    if config_path and os.path.exists(config_path):
         print(f"Using Config File: {config_path}")
    elif args.config:
         print(f"Warning: Config file specified but not found: {config_path}")
         config_path = None # Ensure it's None if not found
    else:
         print("No config file specified, proceeding without class validation.")
    
    if tag_mapping_path and os.path.exists(tag_mapping_path):
        print(f"Using Tag Mapping File: {tag_mapping_path}")
    elif args.tag_mapping:  # Only warn if explicitly specified but not found
        print(f"Warning: Tag mapping file specified but not found: {tag_mapping_path}")
    # Otherwise we'll use the default mapping file in the same directory as process_all_sites.py

    # --- Stage 1: Process Annotations and Run Koogu --- 
    failed_sites = []
    if not args.skip_koogu:
        print("\n=== Stage 1: Processing Annotations and Running Koogu ===")
        # Note: process_site within run_all_sites expects base dirs for annotations and koogu output
        # It will create site-specific subdirectories within them.
        failed_sites = run_all_sites_processing(
            raw_data_dir=raw_data_dir,
            annotations_output_dir=annotations_dir, 
            koogu_output_dir=koogu_output_dir,
            config_path=config_path,
            tag_mapping_path=tag_mapping_path
        )
        if failed_sites:
            print(f"\nWarning: The following sites failed processing: {', '.join(failed_sites)}")
            print("Continuing with spectrograms generation for successful sites...")
        print("=== Stage 1 Completed ===")
    else:
        print("\n=== Skipping Stage 1 (Annotation/Koogu Processing) as requested ===")

    # --- Stage 2: Generate Spectrograms --- 
    print("\n=== Stage 2: Generating Spectrograms ===")
    stage2_success = run_spectrogram_generation(
        koogu_output_dir=koogu_output_dir,
        spectrograms_output_dir=spectrograms_dir,
        clips_output_dir=clips_dir,
        config_path=config_path,
        site_to_process=args.site # Pass the specific site if provided
    )

    if not stage2_success:
        print("\nError: Stage 2 (Spectrogram Generation) failed. Exiting workflow.")
        sys.exit(1)
    print("=== Stage 2 Completed ===")

    # --- Workflow Summary --- 
    print("\n--- Preprocessing Workflow Completed ---")
    if failed_sites:
        print(f"Warning: {len(failed_sites)} sites failed during Stage 1: {', '.join(failed_sites)}")
    if not args.skip_koogu:
        print(f"Annotations saved in subdirectories under: {annotations_dir}")
        print(f"Koogu output saved in subdirectories under: {koogu_output_dir}")
    else:
         print(f"Used existing Koogu output from: {koogu_output_dir}")
    print(f"Spectrograms saved in class directories under: {spectrograms_dir}")
    print(f"Clips saved in site directories under: {clips_dir}")
    # Optional: Verify output structure or counts here if needed
    
    # No temporary files were created, so no cleanup needed.

    print("--- Workflow Finished ---")
    sys.exit(0)


if __name__ == "__main__":
    main() 